// Applied to every generation regardless of platform or style
const ANTI_AI_CONSTRAINT = `写作约束（强制执行，违反即失败）：

禁止以下模式：
- 任何段落前挂粗体标签，如「**落地建议**：」「**选购要点**：」「**设置方法**：」「**总结**：」——直接写内容
- 高频套话：「首先」「其次」「综上」「如今时代」「不得不说」「值得注意的是」「让我们」「毋庸置疑」
- 对称性结构：三点问题对应三点建议对应三点总结，读起来像填表格
- 不同段落用完全相同的句式开头，造成机械感
- 空洞的抽象收尾，如「这就是组网的精髓」「教训很深刻」「希望对你有所帮助」

应该有：
- 不平均的节奏：有地方详细讲一件事，有地方一两句带过，有地方发表评论
- 具体的细节、型号、数字，而不是「速度更快」「效果更好」这类空话
- 包括局限或反面的表达，不要通篇都是正向收益
- 句子长短交替，偶尔用一句极短的话单独成段，制造停顿`

function buildSystemPrompt(platform, style, audience, lengthPref) {
  const platformRule = PLATFORM_RULES[platform] || PLATFORM_RULES.wechat_mp
  const styleInstruction = STYLE_INSTRUCTIONS[style] ||
    `行文风格要求（直接执行，不做解读）：${style}`
  const lengthInstruction = LENGTH_INSTRUCTIONS[lengthPref] || LENGTH_INSTRUCTIONS.medium

  return [
    platformRule,
    styleInstruction,
    lengthInstruction,
    `目标受众：内容面向"${audience}"群体，请确保语言、案例、深度与该群体匹配。`,
    ANTI_AI_CONSTRAINT,
    '重要：直接输出正文内容，不要添加"好的""当然"等开场白，不要解释创作思路。推理阶段只允许思考如何将上述行文风格落实到每一句话——内容结构、话题选择、平台适配已由前面的指令决定，不需要重新推断。',
  ].join('\n\n')
}

function buildUserPrompt(skeleton, refMaterial) {
  let prompt = `请根据以下内容骨架创作完整内容：\n\n${skeleton}`
  if (refMaterial && refMaterial.trim()) {
    prompt += `\n\n参考素材（仅作风格/信息参考，不要直接复制）：\n${refMaterial}`
  }
  return prompt
}

function buildTitlePrompt(content, platform) {
  return (
    `以下是一篇${platform}内容，请为其生成5个吸引眼球的标题候选。\n` +
    `要求：每行一个标题，不带序号，直接输出标题文本。\n\n` +
    `内容：\n${content.slice(0, 500)}`
  )
}

function buildRefinePrompt(selectedText, action, platform, polishInstruction = '') {
  const defaultPolish = `对以下段落进行深度润色，使其读起来像真实的人写的，而不是被生成的。

执行以下规则，逐条落实，不可选择性忽略：

1. 严禁序列连接词：不准出现「首先、其次、再次、最后」「第一、第二、第三」。不准用「综上所述」「总而言之」「有鉴于此」收束。
2. 禁用时代背景套话：不准写「在当今社会」「随着生活节奏的加快」「在物欲横流的时代」这类大而空的起手式。
3. 打破结构化排版：完全不要分点列项，不要加粗小标题，不要编号。段落靠意义和呼吸自然断句，哪怕显得有点散。
4. 破开句式节奏：避免连续三个以上的句子用相同语法开头。强行穿插单字句、断句，比如「好。」「不懂。」「算了。」，把整齐的排比感打碎。
5. 结尾不准升华与号召：禁止在末尾总结、点题、号召行动，也不准出现「让我们一起」「所以，从今天开始」等鼓动性收尾。可以叙述到一个细节突然停住，或用一个淡淡的画面消退。
6. 禁止空洞的营销词：不准使用「重磅来袭」「必入」「神仙」「王炸」「绝绝子」，一律替换为具体的感受、细节或对比。
7. 禁用强逻辑连词：不得使用「以便」「从而」「此外」「不仅如此」「更重要的是」，让句子间的逻辑靠语气自然承接，留出缝隙。
8. 保留口语的毛边：允许插入一句不经意的口语，比如「说真的」「你听我讲」「写到这儿突然想起来……」，允许一个念头没说完就跳到另一个，制造即兴感。
9. 人称必须是「我」和「你」：把所有「笔者」「大家」「我们每个人」换成「我」和「你」，让文字像贴着耳朵说的私语，而不是公开演讲。
10. 接受可控的不完美：故意保留一处半截子话、一个不太准确的词，或一句看似无关的跑题碎碎念，用来破坏过度工整的AI腔。`

  const polishPrompt = polishInstruction
    ? `对以下段落按照如下要求进行改写：\n\n${polishInstruction}\n\n保持原有核心意思，直接输出改写后的内容。`
    : defaultPolish

  const actionMap = {
    expand: '对以下段落进行扩写，丰富细节和论据，保持原有风格和立意',
    shorten: '对以下段落进行精简，保留核心信息，去除冗余表达',
    polish: polishPrompt,
  }
  return (
    `平台：${platform}\n` +
    `任务：${actionMap[action]}。\n` +
    `直接输出处理后的段落，不要添加任何解释。\n\n` +
    `原文：\n${selectedText}`
  )
}

